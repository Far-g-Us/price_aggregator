// Тихий вывод в тестах — подключается один раз через `tsx --import`.
//
// Тесты намеренно идут по отказным путям: сеть молчит, цена NaN, база не
// открыта, каталог пустой. Приложение на каждом таком месте печатает ошибку —
// и это правильно в работе, но в `npm test` десяток строк «ошибок» выглядит как
// упавшая сеть и мешает прочитать результат. Поэтому здесь заглушаются
// `console.error`, `console.warn` и `console.debug`: остаются только итоги
// (`console.log`) и отчёт покрытия.
//
// Логика приложения не меняется: глушится только вывод. Причина падения теста
// идёт через `assert` (исключение), поэтому она всё равно видна. Нужен эхо-режим,
// чтобы разобраться, откуда пришло сообщение:
////   npx tsx --import ./scripts/quiet.mjs scripts/test-services.ts       # тихо//   npx tsx --import ./scripts/quiet.mjs scripts/test-services.ts       # тихо
//   PA_TEST_LOUD=1 npx tsx --import ./scripts/quiet.mjs scripts/test-services.ts  # эхо
//
// Отдельный файл (а не заглушка в каждом тесте) — потому что иначе её надо
// повторять в двадцати файлах и легко забыть в новом.

const LOUD = process.env.PA_TEST_LOUD === '1' || process.env.PA_TEST_LOUD === 'true';

if (!LOUD) {
  console.error = () => {};
  console.warn = () => {};
  console.debug = () => {};
}

