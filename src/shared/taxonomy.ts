/**
 * Совпадение слова с основой.
 *
 * Подстрочный поиск без границ давал ложные срабатывания на живых данных:
 * «игрушка» ловила `груш` (фрукты), «высокобелковое» — `сок` (напитки).
 * Обычные `\b` в JS слепы к кириллице, а жёсткое «основа в начале слова»
 * ломает русские названия: там родительный падеж («пачка масла», «пакет
 * молока»), то есть основа стоит в КОНЦЕ слова.
 *
 * Поэтому слово считается тем же, если выполняется хотя бы одно:
 *  1. слово начинается с основы и длиннее её не более чем на четыре буквы —
 *     падеж и прилагательные: «лимонад», «картофельные», «стирального»;
 *  2. слово короче или равно основе и совпадает с ней без последней буквы —
 *     родительный: «молока»/«молоко», «масла»/«масло», «ягоды»/«ягод».
 *
 * Сравнение идёт с основы, а не по первым буквам, поэтому чужие слова
 * отсекаются сами: «чистая вода» не ловит `чистящ`, «крупинки» не ловят
 * `крупа`, «зеленый чай» не ловит `зелени», «пастеризованное» не ловит
 * `паста`. Настоящие ложные срабатывания остаются только там, где слово
 * РЕАЛЬНО продолжает основу («лимон» → «лимонад», «яблок» → «яблочный»,
 * «слив» → «сливки»), и их снимает exclude у полки.
 *
 * Многословные записи вроде «сливочное масло» или «крем для рук» ищутся
 * подстрокой: они пишутся как есть, и иначе «Пачка масла сливочного»
 * перестала бы попадать в бакалею.
 */
const MAX_ENDING = 4;

function isMultiWord(stem: string): boolean {
  return stem.length > 1 && stem.includes(' ');
}

/** Текст режем на слова один раз на товар, а не на каждую основу. */
function words(text: string): string[] {
  return text.split(/[^\p{L}]+/u).filter(Boolean);
}

function hasStemAtWordStart(tokens: string[], text: string, stem: string): boolean {
  if (isMultiWord(stem)) return text.includes(stem);
  const cut = stem.slice(0, -1);
  const max = stem.length + MAX_ENDING;
  return tokens.some(
    (token) =>
      (token.length <= max && token.startsWith(stem)) ||
      (token.length <= stem.length && token.startsWith(cut)),
  );
}

/**
 * Исключение ищем строго: полное слово должно быть началом слова.
 * Усекать его нельзя — иначе `чай` в exclude съел бы «чайные салфетки»,
 * которые относятся к быту, а не к напиткам.
 */
function hasWordAtWordStart(tokens: string[], text: string, word: string): boolean {
  if (isMultiWord(word)) return text.includes(word);
  return tokens.some((token) => token.startsWith(word));
}

/** Проходит ли товар в нашу категорию по словам в названии. */
export function matchesOurCategory(category: OurCategory, name: string): boolean {
  const lower = name.toLowerCase().replace(/ё/g, 'е');
  const norm = (w: string): string => w.toLowerCase().replace(/ё/g, 'е');
  const tokens = words(lower);
  if (category.exclude?.some((w) => hasWordAtWordStart(tokens, lower, norm(w)))) return false;
  if (!category.include || category.include.length === 0) return true;
  return category.include.some((w) => hasStemAtWordStart(tokens, lower, norm(w)));
}

// Автораскладка: в какие наши категории попадает товар по названию.
// Применяется ко ВСЕМУ, что мы получили из сетей (поиск, категория,
// наши категории), чтобы товар сразу оказывался на полках, а не только
// внутри своей категории. Пустой массив = «не разложено».
// Категории без `include` в автораскладке не участвуют: иначе «без
// фильтра» означало бы «подходит всё подряд».
export function classifyOurCategories(
  name: string,
  all: OurCategory[] = OUR_CATEGORIES,
): string[] {
  return all
    .filter((c) => (c.include?.length ?? 0) > 0 && matchesOurCategory(c, name))
    .map((c) => c.id);
}

export function ourCategoryById(id: string): OurCategory | undefined {
  return OUR_CATEGORIES.find((c) => c.id === id);
}

// `info` — то, что приходит по IPC: id/имя/родитель плюс счётчики.
export interface OurCategoryView {
  id: string;
  name: string;
  parentId: string | null;
  queryCount: number;
  storeCount: number;
  virtual?: boolean;
}

// Какие полки и в каком порядке рисует UI. Раньше здесь была одна функция
// `visibleOurCategories`, но renderer её не вызывал: он строил дерево сам, а
// тест проверял ту функцию — то есть тест был зелёный по коду, которого в
// приложении нет. Сейчас это ровно тот вызов, который делает renderer.
// Фильтр по parentId остаётся осмысленным: полка с проставленным родителем
// молча исчезла бы из списка, а не упала бы, — поэтому ветка покрыта тестом
// на не-плоском входе.
export function rootShelves(all: OurCategoryView[]): OurCategoryView[] {
  return all.filter((c) => c.parentId === null && c.virtual !== true);
}

