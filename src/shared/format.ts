// Цены в приложении показываем целыми рублями: сети отдают цены с
// копейками (219.99), и в карточке это выглядит разнобоем — «229 ₽» против
// «219.99 ₽». В базу копейки пишем как есть (там точность важна), округляем
// только на экране.
export function formatPrice(value: number): string {
  return `${Math.round(value)} ₽`;
}
