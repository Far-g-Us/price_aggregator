/**
 * Единственная точка, где адаптеры достают Playwright.
 *
 * Зачем порт, если импорт и так работает: браузер нельзя поднять в юнит-тесте
 * (это отдельный процесс, сеть и шесть секунд ожидания на сессию), а весь
 * браузерный транспорт — это логика поверх `page`/`context`. Поэтому модуль
 * можно подменить фейком, а поведение по умолчанию остаётся ровно прежним:
 * реальный динамический импорт и та же ошибка при битой установке.
 *
 * Подменяет только тесты (`__setPlaywrightForTests`); в приложении значение
 * всегда `null`, и путь «Playwright нет» остаётся громким.
 *
 * Именно здесь динамический импорт остаётся: заменить его статическим нельзя —
 * пакет `playwright` ставится отдельно (`npx playwright install chromium`), и без
 * него приложение обязано падать громко, а не молча ехать без браузера. Ветка
 * отказа импорта поэтому остаётся непокрытой и помечена `c8 ignore` рядом с
 * вызовом в обоих адаптерах.
 */
let injected: typeof import('playwright') | null = null;

/** Подмена для тестов; `null` — вернуть настоящий модуль. */
export function __setPlaywrightForTests(pw: typeof import('playwright') | null): void {
  injected = pw;
}

export function injectedPlaywright(): typeof import('playwright') | null {
  return injected;
}